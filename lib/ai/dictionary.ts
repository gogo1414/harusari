/**
 * 짧은 별칭(2자 이하 한글, 3자 이하 영문)은 오탐 방지를 위해 "단어 전체 일치"로만 인정한다.
 * 예) '알리'는 '알리오올리오'에 걸리면 안 된다.
 */
export function isShortAlias(alias: string): boolean {
  return /^[A-Za-z0-9]+$/.test(alias) ? alias.length <= 3 : alias.length <= 2;
}
